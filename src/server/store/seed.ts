const t = (date: string) => `${date}T02:00:00.000Z`;

function item(
  partial: Omit<KnowledgeItem, "versions" | "version" | "synthetic" | "supersededById" | "language"> & {
    language?: KnowledgeItem["language"];
  },
): KnowledgeItem {
  return {
    language: "id",
    ...partial,
    version: 1,
    versions: [
      {
        version: 1,
        title: partial.title,
        summary: partial.summary,
        sections: partial.sections,
        editedBy: partial.contributorId,
        editedAt: partial.createdAt,
        changeNote: "Versi awal",
      },
    ],
    supersededById: null,
    synthetic: true,
  };
}

function source(id: string, title: string, originalText: string, createdBy: string, createdAt: string): KnowledgeSource {
  return { id, kind: "manual_entry", title, originalText, conversationId: null, createdBy, createdAt };
}

